// Expands scripts/seed-source.mjs into src/data/seed.json and supabase/seed.sql
import { writeFileSync, mkdirSync } from 'node:fs';
import { categories, services } from './seed-source.mjs';

const catSlugs = new Set(categories.map((c) => c.slug));
for (const s of services) if (!catSlugs.has(s.category)) throw new Error(`Unknown category ${s.category} in ${s.slug}`);
const slugs = new Set();
for (const s of services) { if (slugs.has(s.slug)) throw new Error('Duplicate slug ' + s.slug); slugs.add(s.slug); }

mkdirSync('src/data', { recursive: true });
writeFileSync('src/data/seed.json', JSON.stringify({ categories, services }, null, 1));

const q = (v) => (v === null || v === undefined ? 'null' : `'${String(v).replace(/'/g, "''")}'`);
const j = (v) => `${q(JSON.stringify(v))}::jsonb`;
let sql = `-- GENERATED by scripts/build-seed.mjs — do not edit by hand. Idempotent: safe to re-run.\n-- All content is a draft flagged needs_review = true.\nbegin;\n\n`;
for (const c of categories) {
  sql += `insert into public.categories (slug, icon, position, title_ar, title_en, desc_ar, desc_en) values (${q(c.slug)}, ${q(c.icon)}, ${c.position}, ${q(c.title_ar)}, ${q(c.title_en)}, ${q(c.desc_ar)}, ${q(c.desc_en)})\n  on conflict (slug) do update set icon = excluded.icon, position = excluded.position, title_ar = excluded.title_ar, title_en = excluded.title_en, desc_ar = excluded.desc_ar, desc_en = excluded.desc_en;\n`;
}
sql += '\n';
for (const s of services) {
  sql += `insert into public.services (slug, category_id, title_ar, title_en, summary_ar, summary_en, documents, steps, fees_ar, fees_en, duration_ar, duration_en, location_ar, location_en, links, tips_ar, tips_en, popular, published, needs_review, last_verified)\nvalues (${q(s.slug)}, (select id from public.categories where slug = ${q(s.category)}), ${q(s.title_ar)}, ${q(s.title_en)}, ${q(s.summary_ar)}, ${q(s.summary_en)}, ${j(s.documents)}, ${j(s.steps)}, ${q(s.fees_ar)}, ${q(s.fees_en)}, ${q(s.duration_ar)}, ${q(s.duration_en)}, ${q(s.location_ar)}, ${q(s.location_en)}, ${j(s.links)}, ${q(s.tips_ar)}, ${q(s.tips_en)}, ${s.popular}, ${s.published}, ${s.needs_review}, ${q(s.last_verified)})\non conflict (slug) do nothing;\n`;
}
sql += '\ncommit;\n';
writeFileSync('supabase/seed.sql', sql);
console.log(`seed: ${categories.length} categories, ${services.length} services`);
